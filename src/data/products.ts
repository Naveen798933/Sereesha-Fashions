export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getProductsByCategory(category: string): Product[] {
  if (category === "all") return PRODUCTS;
  return PRODUCTS.filter((p) => p.category.toLowerCase() === category.toLowerCase());
}

export async function fetchProductBySlug(slug: string): Promise<Product | undefined> {
  const local = getProductBySlug(slug);
  if (local) return local;

  try {
    const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
    const supabaseKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
    if (supabaseUrl && supabaseKey) {
      const res = await fetch(
        `${supabaseUrl}/rest/v1/products?slug=eq.${encodeURIComponent(slug)}&select=*`,
        {
          headers: {
            apikey: supabaseKey,
            Authorization: `Bearer ${supabaseKey}`,
          },
          next: { revalidate: 60 },
        }
      );
      if (res.ok) {
        const rows = await res.json();
        if (rows && rows.length > 0) {
          const r = rows[0];
          return {
            id: r.id,
            slug: r.slug,
            title: r.title,
            category: r.category,
            categoryLabel: r.category_label || r.category,
            collection: r.collection,
            price: Number(r.price),
            originalPrice: r.original_price ? Number(r.original_price) : undefined,
            primaryImage: r.primary_image,
            galleryImages: r.gallery_images || [r.primary_image],
            badge: r.badge,
            rating: Number(r.rating || 5),
            reviewCount: Number(r.review_count || 0),
            sizes: r.sizes || [],
            fabric: r.fabric || "",
            weave: r.weave || "",
            color: r.color || "",
            occasion: r.occasion || "",
            silkMarkCertified: Boolean(r.silk_mark_certified),
            blouseIncluded: Boolean(r.blouse_included),
            shortDescription: r.short_description || "",
            description: r.description || "",
            details: r.details || {},
          };
        }
      }
    }
  } catch (err) {
    console.warn("Supabase PDP fetch fallback to local:", err);
  }

  return getProductBySlug(slug);
}
